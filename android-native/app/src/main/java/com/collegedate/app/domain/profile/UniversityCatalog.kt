    fun search(query: String, limit: Int = 30): List<University> {
        val normalized = query.trim().lowercase()
        if (normalized.isBlank()) return universities.take(limit)
        return universities
            .filter { university ->
                university.searchTokens.contains(normalized)
            }
            .take(limit)
    }

    fun contains(name: String): Boolean =
        universities.any { it.name.equals(name.trim(), ignoreCase = true) }
